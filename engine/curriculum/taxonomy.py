"""Canonical TNPSC curriculum loaded from the platform-owned manifest.

The platform syllabus YAML is the source of truth. This checked-in JSON
snapshot is generated by scripts/export-curriculum-manifest.py in the
platform repository. Topic node IDs are intentionally identical to the
platform database topic IDs used by the publication API.
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

from .models import CurriculumNode, CurriculumVersion, CurriculumStatus, NodeType


_MANIFEST_PATH = Path(__file__).with_name("platform_manifest.json")
_MANIFEST = json.loads(_MANIFEST_PATH.read_text(encoding="utf-8"))

CURRICULA = tuple(
    CurriculumVersion(
        id=item["id"],
        exam_code=item["exam_code"],
        source_reference=item["source_reference"],
        effective_from=date.fromisoformat(item["effective_from"]),
        status=CurriculumStatus(item["status"]),
    )
    for item in _MANIFEST["curricula"]
)

NODES = tuple(
    CurriculumNode(
        id=item["id"],
        curriculum_version_id=item["curriculum_version_id"],
        node_type=NodeType(item["node_type"]),
        canonical_key=item["canonical_key"],
        title_en=item["title_en"],
        title_ta=item.get("title_ta"),
        parent_id=item.get("parent_id"),
        aliases=tuple(item.get("aliases") or ()),
        sort_order=int(item.get("sort_order", 0)),
    )
    for item in _MANIFEST["nodes"]
)

CURRICULUM = next(item for item in CURRICULA if item.id == "tnpsc-prelims-495")
CURRICULUM_MAINS_583 = next(
    item for item in CURRICULA if item.id == "tnpsc-group-2a-mains-583"
)

SUBJECTS = tuple(
    node for node in NODES
    if node.curriculum_version_id == CURRICULUM.id and node.node_type is NodeType.SUBJECT
)

TOPIC_NODES = tuple(node for node in NODES if node.node_type is NodeType.TOPIC)
TOPIC_IDS = frozenset(node.id for node in TOPIC_NODES)
PLATFORM_TOPIC_IDS = TOPIC_IDS


def get_curriculum_nodes(curriculum_id: str | None = None) -> tuple[CurriculumNode, ...]:
    if curriculum_id is None:
        return NODES
    return tuple(node for node in NODES if node.curriculum_version_id == curriculum_id)


def get_topic_ids(curriculum_id: str | None = None) -> frozenset[str]:
    return frozenset(
        node.id for node in TOPIC_NODES
        if curriculum_id is None or node.curriculum_version_id == curriculum_id
    )


def general_studies_units() -> tuple[CurriculumNode, ...]:
    subject = next(node for node in SUBJECTS if node.canonical_key == "general-studies")
    return tuple(
        node for node in NODES
        if node.curriculum_version_id == CURRICULUM.id
        and node.node_type is NodeType.UNIT
        and node.parent_id == subject.id
    )
